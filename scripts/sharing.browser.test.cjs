const test = require('node:test');
const assert = require('node:assert/strict');
const { chromium } = require('@playwright/test');
const { fixture } = require('../server/test-support.cjs');

test('invite links survive login; trip menu exposes receipts, guest links and confirmed arrival', { timeout: 120000 }, async t => {
  const { call, user, base } = await fixture(t);
  const alice = await user('sharing-alice'), bob = await user('sharing-bob');
  const invitation = (await call('circle/links', alice.token, {})).body.link;
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
  t.after(async () => { await context.close(); await browser.close(); });
  await context.route('**/api/auth/**', async route => {
    const url = new URL(route.request().url());
    try { await route.fulfill({ response: await route.fetch({ url: base + url.pathname.split('/api/auth/')[1] + url.search, timeout: 30000 }) }); }
    catch { await route.abort().catch(() => {}); }
  });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`http://localhost:8081/#invite=${invitation.token}`);
  await page.getByLabel('Email', { exact: true }).fill(bob.user.email);
  await page.getByLabel('Пароль', { exact: true }).fill('test-password-2026');
  await page.getByRole('button', { name: 'Войти', exact: true }).click();
  await page.getByRole('button', { name: 'Проверить приглашение', exact: true }).click();
  await page.getByText(alice.user.name, { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Принять и добавить контакт', exact: true }).click();
  await page.getByText('Контакт добавлен', { exact: true }).waitFor();
  assert.equal((await call('circle/contacts', bob.token)).body.people[0].connectionStatus, 'accepted');
  assert.equal(new URL(page.url()).hash, '');
  await page.getByRole('button', { name: 'Создать приглашение', exact: true }).click();
  await page.getByRole('button', { name: 'Поделиться ссылкой', exact: true }).waitFor();
  await page.screenshot({ path: '.preview/contact-link-redesign-mobile.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Отозвать приглашение', exact: true }).click();
  await page.getByRole('button', { name: 'Поделиться ссылкой', exact: true }).waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Закрыть', exact: true }).last().click();
  const point = { name: 'Тестовый парк', latitude: 43.24, longitude: 76.93 };
  const trip = (await call('journeys', bob.token, { clientId: 'sharing_browser_trip', origin: point, target: point, transport: 'walk', minutes: 15, accompanied: true, route: { distance: 1000, duration: 900, coordinates: [point, point] } })).body.journey;
  assert.equal(trip.status, 'active');
  await page.reload();
  await page.getByRole('tab', { name: 'Маршруты', exact: true }).click();
  await page.getByRole('button', { name: 'Я на месте', exact: true }).waitFor();
  await page.screenshot({ path: '.preview/routes-redesign-active.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Ещё', exact: true }).click();
  await page.getByRole('button', { name: 'Статус уведомлений', exact: true }).click();
  await page.getByText('Сохранено на сервере', { exact: true }).waitFor();
  const message = (await call(`notifications/sent?journeyId=${trip.id}`, bob.token)).body.messages[0];
  await call('notifications/received', alice.token, { ids: [message.id] });
  await page.getByText('Получено приложением', { exact: true }).waitFor();
  await call(`circle/chats/${bob.user.id}/read`, alice.token, { lastId: message.id }, 'PUT');
  await page.getByText('Прочитано', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Закрыть', exact: true }).last().click();
  await page.getByRole('button', { name: 'Ещё', exact: true }).click();
  await page.getByRole('button', { name: 'Ссылка на поездку', exact: true }).click();
  await page.getByRole('button', { name: 'Разрешить передачу геопозиции', exact: true }).click();
  const createdResponse = page.waitForResponse(response => response.url().endsWith('/safety/links') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Создать временную ссылку', exact: true }).click();
  const created = await (await createdResponse).json();
  await page.getByRole('button', { name: 'Поделиться ссылкой', exact: true }).waitFor();
  const guest = await context.newPage();
  await guest.goto(base.replace('/api/auth/', '') + created.link.path);
  await guest.getByRole('heading', { name: point.name, exact: true }).waitFor();
  await page.getByRole('button', { name: 'Закрыть', exact: true }).last().click();
  await page.getByRole('button', { name: 'Я на месте', exact: true }).click();
  await page.getByText('Вы точно на месте?', { exact: true }).waitFor();
  assert.equal((await call('journeys/state', bob.token)).body.active.id, trip.id);
  await page.getByRole('button', { name: 'Нет, ещё в пути', exact: true }).click();
  assert.equal((await call('journeys/state', bob.token)).body.active.id, trip.id);
  await page.getByRole('button', { name: 'Я на месте', exact: true }).click();
  await page.getByRole('button', { name: 'Да, я на месте', exact: true }).click();
  await page.getByRole('button', { name: 'Я на месте', exact: true }).waitFor({ state: 'hidden' });
  assert.equal((await call('journeys/state', bob.token)).body.active, null);
  await page.getByRole('button', { name: 'История', exact: true }).click();
  await page.screenshot({ path: '.preview/routes-redesign-history.png', fullPage: true, animations: 'disabled' });
  const deletion = page.getByRole('button', { name: `Удалить запись: ${point.name}`, exact: true });
  await deletion.click();
  await page.getByRole('button', { name: 'Оставить', exact: true }).click();
  await deletion.waitFor();
  await page.getByRole('button', { name: 'Очистить историю', exact: true }).click();
  await page.getByRole('button', { name: 'Очистить историю', exact: true }).last().click();
  await page.getByText('История пуста', { exact: true }).waitFor();
  await page.screenshot({ path: '.preview/routes-simplified.png', fullPage: true, animations: 'disabled' });
  assert.deepEqual((await call('journeys/state', bob.token)).body.history, []);
  assert.deepEqual(errors, []);
});
