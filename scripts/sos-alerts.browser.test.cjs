const test = require('node:test');
const assert = require('node:assert/strict');
const { chromium } = require('@playwright/test');
const { fixture } = require('../server/test-support.cjs');

test('SOS interrupts dialogs and active chats, persists, queues and requires a successful acknowledgement', { timeout: 90000 }, async t => {
  const { call, user, base } = await fixture(t);
  const sender = await user('sos-browser-sender'), recipient = await user('sos-browser-recipient');
  await call('circle/contacts', sender.token, { email: recipient.user.email });
  await call(`circle/invitations/${sender.user.id}/respond`, recipient.token, { decision: 'accepted' });
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, permissions: ['geolocation'], geolocation: { latitude: 43.24, longitude: 76.93 } });
  t.after(async () => { await context.close(); await browser.close(); });
  let rejectAck = true;
  let failRouteOnce = true;
  await context.route('**/api/auth/**', async route => {
    const url = new URL(route.request().url());
    if (url.pathname.endsWith('/maps/route')) {
      const body = route.request().postDataJSON();
      assert.equal(body.origin.latitude, 43.24);
      assert.equal(body.target.longitude, 76.94);
      if (failRouteOnce) { failRouteOnce = false; return route.fulfill({ status: 503, json: { message: 'Тест: маршрут недоступен' } }); }
      return route.fulfill({ json: { distance: 1200, duration: 600, coordinates: [body.origin, body.target] } });
    }
    if (rejectAck && url.pathname.includes('/sos/') && url.pathname.endsWith('/acknowledge')) return route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: 'Тест: нет соединения' }) });
    try { await route.fulfill({ response: await route.fetch({ url: base + url.pathname.split('/api/auth/')[1] + url.search }) }); }
    catch { await route.abort().catch(() => {}); }
  });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://localhost:8081');
  await page.getByLabel('Email', { exact: true }).fill(recipient.user.email);
  await page.getByLabel('Пароль', { exact: true }).fill('test-password-2026');
  await page.getByRole('button', { name: 'Войти', exact: true }).click();
  await page.getByRole('tab', { name: 'Контакты', exact: true }).click();
  await page.getByRole('button', { name: 'Добавить контакт', exact: true }).first().click();
  await page.getByRole('button', { name: 'Приглашение по ссылке', exact: true }).waitFor();
  await call('journeys/sos/send', sender.token, { clientId: 'browser_urgent_01', includeLocation: false });
  const urgent = page.getByText('СРОЧНАЯ ТРЕВОГА', { exact: true });
  await urgent.waitFor();
  assert.equal(await page.getByRole('button', { name: 'Приглашение по ссылке', exact: true }).count(), 0);
  await page.getByText(sender.user.name, { exact: true }).last().waitFor();
  await page.screenshot({ path: '.preview/sos-urgent-mobile.png', fullPage: true, animations: 'disabled' });
  await call(`circle/chats/${recipient.user.id}/messages`, sender.token, { text: 'Обычное сообщение', clientId: 'sos_regular_after' });
  await page.waitForTimeout(8500);
  assert.equal(await urgent.count(), 1);
  await call('journeys/sos/send', sender.token, { clientId: 'browser_urgent_02', includeLocation: false });
  await page.getByText('Ещё тревог: 1', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Получил SOS, связываюсь', exact: true }).click();
  await page.getByText('Тест: нет соединения', { exact: true }).waitFor();
  assert.equal(await urgent.count(), 1);
  rejectAck = false;
  await page.getByRole('button', { name: 'Получил SOS, связываюсь', exact: true }).click();
  await page.getByText('Ещё тревог: 1', { exact: true }).waitFor({ state: 'hidden' });
  assert.equal((await call('notifications/sos', recipient.token)).body.alerts.length, 1);
  await page.screenshot({ path: '.preview/sos-after-ack.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Открыть чат', exact: true }).click();
  await urgent.waitFor({ state: 'hidden' });
  await page.getByLabel('Сообщение', { exact: true }).waitFor();
  await call('journeys/sos/send', sender.token, { clientId: 'browser_urgent_03', includeLocation: true, note: 'Не могу говорить', position: { latitude: 43.25, longitude: 76.94, capturedAt: Date.now() } });
  await urgent.waitFor();
  await page.getByRole('button', { name: 'Скрыть тревогу', exact: true }).click();
  await page.getByRole('tab', { name: 'Маршруты', exact: true }).click();
  await page.getByText('НУЖНА ПОМОЩЬ', { exact: true }).first().waitFor();
  await page.getByRole('button', { name: 'Местоположение', exact: true }).first().click();
  await page.evaluate(() => { window.open = () => { throw new Error('SOS route must stay in SafeWalk'); }; });
  await page.getByRole('button', { name: 'Построить маршрут', exact: true }).click();
  await page.getByText('Тест: маршрут недоступен', { exact: true }).waitFor();
  assert.equal((await call('journeys/state', sender.token)).body.sentSOS.find(item => item.clientId === 'browser_urgent_03').routeStartedAt, null);
  await page.getByRole('button', { name: 'Построить маршрут', exact: true }).click();
  await page.getByText('10 мин', { exact: true }).waitFor();
  await page.getByText(/1,2.*км/).waitFor();
  assert.equal(new URL(page.url()).hostname, 'localhost');
  await page.getByText('SOS обработан. Отправитель знает, что вы направляетесь к нему.', { exact: true }).waitFor();
  assert.ok((await call('journeys/state', sender.token)).body.sentSOS.find(item => item.clientId === 'browser_urgent_03').routeStartedAt);
  await page.screenshot({ path: '.preview/sos-location-note.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Закрыть', exact: true }).last().click();
  await page.screenshot({ path: '.preview/routes-urgent-sos.png', fullPage: true, animations: 'disabled' });
  const receipt = page.waitForResponse(response => response.url().includes('/sos/') && response.url().endsWith('/acknowledge'));
  await page.getByRole('button', { name: 'Получил SOS, связываюсь', exact: true }).first().click();
  assert.equal((await receipt).status(), 200);
  await page.getByRole('button', { name: 'Открыть SOS', exact: true }).click();
  await page.getByRole('button', { name: 'Не могу говорить', exact: true }).click();
  assert.equal(await page.getByLabel('Послание SOS', { exact: true }).inputValue(), 'Не могу говорить');
  const sending = page.waitForRequest(request => request.url().endsWith('/journeys/sos/send') && request.method() === 'POST');
  assert.equal(await page.getByRole('checkbox', { name: 'Тестовый режим SOS', exact: true }).count(), 0);
  await page.screenshot({ path: '.preview/sos-simple-default-location.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Отправить SOS', exact: true }).click();
  const sentBody = (await sending).postDataJSON();
  assert.equal(sentBody.note, 'Не могу говорить');
  assert.equal(sentBody.includeLocation, true);
  assert.equal(sentBody.position.latitude, 43.24);
  await page.getByRole('button', { name: 'Отправить SOS', exact: true }).waitFor({ state: 'hidden' });
  await page.evaluate(() => {
    const query = navigator.permissions.query.bind(navigator.permissions);
    navigator.permissions.query = descriptor => descriptor.name === 'geolocation' ? Promise.resolve({ state: 'denied' }) : query(descriptor);
  });
  await page.getByRole('button', { name: 'Открыть SOS', exact: true }).click();
  await page.getByRole('button', { name: 'Встреть меня', exact: true }).click();
  await page.getByRole('button', { name: 'Отправить SOS', exact: true }).click();
  await page.getByText('Геопозиция отключена', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Проверить и отправить SOS', exact: true }).waitFor();
  await page.screenshot({ path: '.preview/sos-location-settings.png', fullPage: true, animations: 'disabled' });
  const fallback = page.waitForRequest(request => request.url().endsWith('/journeys/sos/send') && request.method() === 'POST');
  await page.getByRole('button', { name: 'Отправить без геопозиции', exact: true }).click();
  const fallbackBody = (await fallback).postDataJSON();
  assert.equal(fallbackBody.includeLocation, false);
  assert.equal(fallbackBody.note, 'Встреть меня');
  assert.deepEqual(errors, []);
});
