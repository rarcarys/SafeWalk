const test = require('node:test');
const assert = require('node:assert/strict');
const { chromium } = require('@playwright/test');
const sharp = require('sharp');
const { fixture } = require('../server/test-support.cjs');

test('profile avatar presets, file upload, reload and removal use server storage', { timeout: 90000 }, async t => {
  const { call, user, base } = await fixture(t);
  const owner = await user('avatar-browser');
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
  t.after(async () => { await context.close(); await browser.close(); });
  await context.route('**/api/auth/**', async route => {
    const url = new URL(route.request().url());
    try { await route.fulfill({ response: await route.fetch({ url: base + url.pathname.split('/api/auth/')[1] + url.search }) }); }
    catch { await route.abort().catch(() => {}); }
  });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://localhost:8081');
  await page.getByLabel('Email', { exact: true }).fill(owner.user.email);
  await page.getByLabel('Пароль', { exact: true }).fill('test-password-2026');
  await page.getByRole('button', { name: 'Войти', exact: true }).click();
  await page.getByRole('button', { name: 'Открыть профиль', exact: true }).click();
  await page.getByRole('button', { name: 'Изменить аватар', exact: true }).click();
  await page.getByRole('button', { name: 'Аватар: Луна', exact: true }).click();
  await page.getByRole('button', { name: 'Сохранить аватар', exact: true }).click();
  await page.getByRole('button', { name: 'Изменить аватар', exact: true }).waitFor();
  assert.equal((await call('me', owner.token)).body.user.avatar, 'preset:moon');
  await page.reload();
  await page.getByRole('button', { name: 'Открыть профиль', exact: true }).click();
  await page.getByRole('button', { name: 'Изменить аватар', exact: true }).click();
  const chooser = page.waitForEvent('filechooser');
  await page.getByRole('button', { name: 'Загрузить фото', exact: true }).click();
  await (await chooser).setFiles({ name: 'avatar.png', mimeType: 'image/png', buffer: await sharp({ create: { width: 100, height: 200, channels: 3, background: '#496bc8' } }).png().toBuffer() });
  await page.getByRole('button', { name: 'Сохранить аватар', exact: true }).click();
  await page.getByRole('button', { name: `Посмотреть аватар: ${owner.user.name}`, exact: true }).getByRole('img').waitFor();
  await page.getByRole('button', { name: `Посмотреть аватар: ${owner.user.name}`, exact: true }).click();
  const closeViewer = page.getByRole('button', { name: 'Закрыть просмотр аватара', exact: true }).last();
  await closeViewer.waitFor();
  const enlarged = await page.getByRole('img', { name: 'Аватар крупным планом', exact: true }).boundingBox();
  assert.ok(enlarged.width > 250 && enlarged.height > 250);
  await closeViewer.click();
  assert.ok((await call('me', owner.token)).body.user.avatar.startsWith('data:image/jpeg;base64,'));
  await page.screenshot({ path: '.preview/avatar-profile.png', fullPage: true });
  const peer = await user('pending-avatar');
  await call('account/avatar', peer.token, { avatar: (await call('me', owner.token)).body.user.avatar }, 'PUT');
  await call('circle/contacts', owner.token, { email: peer.user.email });
  await page.getByRole('tab', { name: 'Контакты', exact: true }).click();
  const pendingContact = page.getByRole('button', { name: `Контакт ${peer.user.name}`, exact: true });
  await pendingContact.getByText('Ожидает принятия', { exact: true }).waitFor();
  const photoBox = await pendingContact.getByRole('img').boundingBox();
  assert.ok(photoBox && photoBox.width === 44 && photoBox.height === 44, 'pending contact photo keeps its square size');
  await pendingContact.getByRole('button', { name: `Посмотреть аватар: ${peer.user.name}`, exact: true }).click();
  await page.getByRole('img', { name: 'Аватар крупным планом', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Закрыть просмотр аватара', exact: true }).last().click();
  await page.screenshot({ path: '.preview/pending-avatar.png', fullPage: true });
  await pendingContact.click();
  await page.getByRole('button', { name: 'Написать', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Удалить контакт', exact: true }).count(), 0);
  assert.equal(await page.getByRole('button', { name: 'Заблокировать пользователя', exact: true }).count(), 0);
  await page.screenshot({ path: '.preview/contact-card-simple.png', fullPage: true });
  await page.getByRole('button', { name: 'Ещё: контакт', exact: true }).click();
  await page.getByRole('button', { name: 'Изменить контакт', exact: true }).click();
  await page.getByRole('textbox', { name: 'Имя контакта', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Закрыть', exact: true }).last().click();
  await page.getByRole('button', { name: 'Открыть профиль', exact: true }).click();
  await page.getByRole('button', { name: 'Изменить аватар', exact: true }).click();
  await page.getByRole('button', { name: 'Убрать аватар', exact: true }).click();
  await page.getByRole('button', { name: 'Сохранить аватар', exact: true }).click();
  await page.getByRole('button', { name: 'Изменить аватар', exact: true }).waitFor();
  assert.equal((await call('me', owner.token)).body.user.avatar, null);
  assert.deepEqual(errors, []);
});
