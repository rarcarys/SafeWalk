const test = require('node:test');
const assert = require('node:assert/strict');
const { fixture } = require('./test-support.cjs');

test('explicit contact and trip consent, location privacy, blocking', async t => {
  const { call, user } = await fixture(t);
  const alice = await user('alice'), bob = await user('bob'), outsider = await user('outsider');
  await call('circle/contacts', alice.token, { email: bob.user.email });
  assert.equal((await call(`circle/chats/${bob.user.id}/messages`, alice.token, { text: 'Hello', clientId: 'pending_message' })).status, 403);
  const origin = { name: 'Start', latitude: 43, longitude: 76 }, target = { name: 'Home', latitude: 43.1, longitude: 76.1 };
  const plan = { clientId: 'consent_journey', origin, target, transport: 'walk', minutes: 10, accompanied: true, route: { distance: 1000, duration: 600, coordinates: [origin, target] } };
  assert.equal((await call('journeys', alice.token, plan)).status, 403);
  assert.equal((await call(`circle/invitations/${alice.user.id}/respond`, outsider.token, { decision: 'accepted' })).status, 404);
  await call(`circle/invitations/${alice.user.id}/respond`, bob.token, { decision: 'accepted' });
  await call('journeys/preferences', alice.token, { sharing: true }, 'PUT');
  const pending = (await call('journeys', alice.token, plan)).body.journey;
  assert.equal(pending.status, 'pending');
  let shared = (await call('journeys/state', bob.token)).body.received[0];
  assert.equal(shared.consent, 'pending'); assert.equal(shared.target.latitude, undefined);
  assert.equal((await call(`journeys/${pending.id}/action`, alice.token, { action: 'arrive', clientId: 'pending_arrival' })).status, 409);
  assert.equal((await call(`journeys/${pending.id}/respond`, outsider.token, { decision: 'accepted' })).status, 404);
  await call(`journeys/${pending.id}/respond`, bob.token, { decision: 'accepted' });
  assert.equal((await call('journeys/state', alice.token)).body.active.status, 'active');
  shared = (await call('journeys/state', bob.token)).body.received[0];
  assert.equal(shared.target.latitude, target.latitude);
  await call('journeys/sos/send', alice.token, { clientId: 'received_sos_key', includeLocation: false });
  assert.equal((await call(`journeys/sos/${alice.user.id}/received_sos_key/acknowledge`, outsider.token, {})).status, 403);
  assert.equal((await call(`journeys/sos/${alice.user.id}/received_sos_key/acknowledge`, bob.token, {})).status, 200);
  assert.ok((await call('journeys/state', alice.token)).body.sentSOS[0].acknowledgedAt);
  await call(`circle/blocks/${alice.user.id}`, bob.token, {});
  assert.equal((await call(`circle/chats/${bob.user.id}/messages`, alice.token, { text: 'Blocked', clientId: 'blocked_message' })).status, 403);
  assert.deepEqual((await call('journeys/state', bob.token)).body.received, []);
  assert.equal((await call('journeys/sos/send', alice.token, { clientId: 'blocked_sos_key', includeLocation: false })).status, 400);
  await call(`circle/blocks/${alice.user.id}`, bob.token, {}, 'DELETE');
  assert.equal((await call(`circle/chats/${bob.user.id}/messages`, alice.token, { text: 'Still no consent', clientId: 'unblocked_message' })).status, 403);
  assert.equal((await call('account/delete', alice.token, { password: 'test-password-2026', confirmation: 'DELETE' })).status, 200);
  const remaining = (await call('circle/contacts', bob.token)).body;
  assert.equal(remaining.people.length, 0);
  assert.equal(remaining.primaryId, null);
  assert.deepEqual((await call('journeys/state', bob.token)).body.receivedSOS, []);
});
