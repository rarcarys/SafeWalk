const { AsyncLocalStorage } = require('node:async_hooks');
const fs = require('node:fs');
const path = require('node:path');

// Keep the existing parameterized statements usable on both engines. Values
// always travel separately from SQL; only application-owned SQL is translated.
function postgresSQL(source) {
  let sql = source.replace(/\bAS\s+([a-z]\w*[A-Z]\w*)\b/g, 'AS "$1"')
    .replace(/\b(?:c\.)?rowid\b/g, match => match.startsWith('c.') ? 'c.sort_order' : 'sort_order')
    .replace(/\bINTEGER\b/g, 'BIGINT')
    .replace(/BIGINT PRIMARY KEY AUTOINCREMENT/g, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/CREATE TABLE IF NOT EXISTS circle_contacts\s*\(/, '$& sort_order BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,')
    .replace(/MAX\(last_id, excluded\.last_id\)/g, 'GREATEST(chat_reads.last_id, excluded.last_id)')
    .replace(/MAX\(expected_at, \?\)/g, 'GREATEST(expected_at, ?)')
    .replace(/SET revision = revision \+ 1/g, 'SET revision = sync_revisions.revision + 1');
  let index = 0;
  // Quoted literals and comments must not consume parameter positions.
  sql = sql.replace(/'(?:''|[^'])*'|"(?:""|[^"])*"|--[^\n]*|\/\*[\s\S]*?\*\/|\?/g, token => token === '?' ? `$${++index}` : token);
  if (/^\s*INSERT OR IGNORE\b/i.test(sql)) {
    sql = sql.replace(/INSERT OR IGNORE/i, 'INSERT').replace(/;\s*$/, '');
    sql += ' ON CONFLICT DO NOTHING';
  }
  return sql;
}

function postgresDDL(source) {
  let sql = source.replace(/PRAGMA\s+[^;]+;/g, '');
  sql = sql.replace(/CREATE TRIGGER IF NOT EXISTS (\w+) AFTER (INSERT|UPDATE|DELETE) ON (\w+)\s*(?:WHEN ([\s\S]*?)\s+)?BEGIN\s*([\s\S]*?)\s*END(?:;|$)/g,
    (_match, name, action, table, condition, statements) => {
      const body = statements.split(';').filter(part => part.trim()).map(postgresSQL).join(';\n') + ';';
      return `CREATE OR REPLACE FUNCTION ${name}_fn() RETURNS trigger LANGUAGE plpgsql AS $trigger$ BEGIN\n${body}\nRETURN NULL; END; $trigger$;\nDROP TRIGGER IF EXISTS ${name} ON ${table};\nCREATE TRIGGER ${name} AFTER ${action} ON ${table} FOR EACH ROW ${condition ? `WHEN (${condition}) ` : ''}EXECUTE FUNCTION ${name}_fn();`;
    });
  return postgresSQL(sql);
}

async function openDatabase({ databasePath, databaseUrl, databaseSchema } = {}) {
  const dialect = databaseUrl ? 'postgres' : 'sqlite';
  const context = new AsyncLocalStorage();
  let tail = Promise.resolve();
  const serial = async operation => {
    if (context.getStore()) return operation();
    const previous = tail;
    let release;
    tail = new Promise(resolve => { release = resolve; });
    await previous;
    try { return await context.run({}, operation); } finally { release(); }
  };
  let sqlite, pool;
  if (dialect === 'postgres') {
    const { Pool, types } = require('pg');
    // IDs and millisecond timestamps have the same JSON representation as SQLite.
    types.setTypeParser(20, value => {
      const number = Number(value);
      if (!Number.isSafeInteger(number)) throw new RangeError('Database integer exceeds JSON safe range');
      return number;
    });
    if (databaseSchema && !/^[a-z_][a-z0-9_]{0,62}$/.test(databaseSchema)) throw new Error('Invalid database schema');
    pool = new Pool({ connectionString: databaseUrl, max: 10, connectionTimeoutMillis: 10000, statement_timeout: 30000, idle_in_transaction_session_timeout: 60000, application_name: 'safewalk', ...(databaseSchema ? { options: `-c search_path=${databaseSchema}` } : {}) });
    pool.on('error', error => console.error('PostgreSQL connection:', error.code || error.name));
    try {
      if (databaseSchema) await pool.query(`CREATE SCHEMA IF NOT EXISTS "${databaseSchema}"`);
      await pool.query('SELECT 1');
    } catch (error) { await pool.end(); throw error; }
  } else {
    const { DatabaseSync } = require('node:sqlite');
    databasePath ||= path.resolve(__dirname, '..', '.data', 'accounts.sqlite');
    fs.mkdirSync(path.dirname(databasePath), { recursive: true });
    sqlite = new DatabaseSync(databasePath);
  }
  const query = (sql, values = []) => serial(async () => {
    if (sqlite) return sqlite.prepare(sql).all(...values);
    const pragma = /^PRAGMA table_info\((\w+)\)$/.exec(sql);
    if (pragma) return (await (context.getStore()?.client || pool).query('SELECT column_name AS name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = $1', [pragma[1]])).rows;
    return (await (context.getStore()?.client || pool).query(postgresSQL(sql), values)).rows;
  });
  const database = {
    dialect,
    prepare(sql) {
      return {
        all: (...values) => query(sql, values),
        get: async (...values) => (await query(sql, values))[0],
        run: (...values) => serial(async () => {
          if (sqlite) return sqlite.prepare(sql).run(...values);
          let translated = postgresSQL(sql);
          if (/^\s*INSERT(?: OR IGNORE)? INTO (chat_messages|push_jobs)\b/i.test(sql)) translated += ' RETURNING id';
          const result = await (context.getStore()?.client || pool).query(translated, values);
          return { changes: result.rowCount, lastInsertRowid: result.rows[0]?.id };
        }),
      };
    },
    exec: sql => serial(async () => {
      if (sqlite) return sqlite.exec(sql);
      const translated = postgresDDL(sql);
      if (translated.trim()) await (context.getStore()?.client || pool).query(translated);
    }),
    transaction: operation => serial(async () => {
      const store = context.getStore();
      if (store.inTransaction) return operation();
      const client = pool ? await pool.connect() : null;
      const execute = sql => client ? client.query(sql) : sqlite.exec(sql);
      store.client = client;
      store.inTransaction = true;
      try {
        await execute('BEGIN');
        // A second API process must not race the safety schedulers or outbox.
        if (client) await execute("SELECT pg_advisory_xact_lock(hashtextextended(current_database() || ':' || current_schema(), 0))");
        const result = await operation();
        await execute('COMMIT');
        return result;
      } catch (error) {
        try { await execute('ROLLBACK'); } catch { /* Preserve the original failure. */ }
        throw error;
      } finally { store.inTransaction = false; delete store.client; client?.release(); }
    }),
    // Send the HTTP result only after the transaction has committed.
    handle: handler => async (request, response, next) => {
      const json = response.json;
      let payload, ready = false;
      response.json = value => { payload = value; ready = true; return response; };
      try {
        await database.transaction(() => handler(request, response, next));
        response.json = json;
        if (ready && !response.destroyed) json.call(response, payload);
      } finally { response.json = json; }
    },
    close: () => serial(async () => { if (sqlite) sqlite.close(); else await pool.end(); }),
  };
  return database;
}

const mapAsync = async (items, operation) => {
  const result = [];
  for (let index = 0; index < items.length; index++) result.push(await operation(items[index], index, items));
  return result;
};
const filterAsync = async (items, operation) => {
  const result = [];
  for (const item of items) if (await operation(item)) result.push(item);
  return result;
};
const someAsync = async (items, operation) => { for (const item of items) if (await operation(item)) return true; return false; };
const everyAsync = async (items, operation) => { for (const item of items) if (!await operation(item)) return false; return true; };
module.exports = { openDatabase, postgresSQL, postgresDDL, mapAsync, filterAsync, someAsync, everyAsync };
