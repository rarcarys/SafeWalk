const test = require('node:test');
const assert = require('node:assert/strict');
const { fixture } = require('./test-support.cjs');

test('urgent SOS feed uses real events, survives read cursors and clears on acknowledgement or block', async t => {
  const { call, user } = await fixture(t);
  const a = await user('sos-alert-a'), b = await user('sos-alert-b'), c = await user('sos-alert-c');
  await call('circle/contacts', a.token, { email: b.user.email });
  await call(`circle/invitations/${a.user.id}/respond`, b.token, { decision: 'accepted' });
  await call(`circle/chats/${b.user.id}/messages`, a.token, { text: 'SOS fake chat', clientId: 'sos_fake_text_01' });
  const alerts = async person => (await call('notifications/sos', person.token)).body.alerts;
  assert.deepEqual(await alerts(b), []);
  assert.equal((await call('notifications/sos')).status, 401);
  const position = { latitude: 43.24, longitude: 76.93, capturedAt: Date.now() };
  await call('journeys/sos/send', a.token, { clientId: 'urgent_sos_event_01', includeLocation: true, position, note: 'Не могу говорить' });
  const details = await call(`journeys/sos/${a.user.id}/urgent_sos_event_01`, b.token);
  assert.equal(details.body.sos.note, 'Не могу говорить');
  assert.equal(details.body.sos.position.latitude, position.latitude);
  assert.equal((await call(`journeys/sos/${a.user.id}/urgent_sos_event_01`, c.token)).status, 403);
  assert.equal((await call('journeys/sos/send', a.token, { clientId: 'invalid_sos_note', includeLocation: false, note: 'a'.repeat(281) })).status, 400);
  const first = (await alerts(b))[0];
  assert.equal(first.senderId, a.user.id);
  assert.equal(first.senderName, a.user.name);
  assert.equal(first.clientId, 'urgent_sos_event_01');
  assert.equal(first.kind, 'sos');
  assert.deepEqual(await alerts(c), []);
  assert.deepEqual(await alerts(a), []);
  await call(`circle/chats/${a.user.id}/read`, b.token, { lastId: first.id }, 'PUT');
  assert.equal((await alerts(b)).length, 1);
  await call('journeys/sos/send', a.token, { clientId: 'urgent_sos_event_02', includeLocation: false });
  assert.equal((await alerts(b)).length, 2);
  assert.equal((await call(`journeys/sos/${a.user.id}/urgent_sos_event_01/navigate`, c.token, {})).status, 403);
  assert.equal((await call(`journeys/sos/${a.user.id}/urgent_sos_event_02/navigate`, b.token, {})).status, 409);
  for (let n = 0; n < 2; n++) assert.equal((await call(`journeys/sos/${a.user.id}/urgent_sos_event_01/navigate`, b.token, {})).status, 200);
  const messages = (await call(`circle/chats/${b.user.id}/messages`, a.token)).body.messages;
  assert.equal(messages.filter(message => message.text.includes('построил(а) маршрут к вам')).length, 1);
  const received = (await call('journeys/state', b.token)).body.receivedSOS.find(item => item.clientId === 'urgent_sos_event_01');
  assert.ok(received.acknowledgedAt);
  assert.ok(received.routeStartedAt);
  assert.ok((await call('journeys/state', a.token)).body.sentSOS.find(item => item.clientId === 'urgent_sos_event_01').routeStartedAt);
  assert.equal((await alerts(b)).length, 1);
  assert.equal((await alerts(b))[0].clientId, 'urgent_sos_event_02');
  await call(`circle/blocks/${a.user.id}`, b.token, {});
  assert.deepEqual(await alerts(b), []);
  assert.equal((await call(`journeys/sos/${a.user.id}/urgent_sos_event_01`, b.token)).status, 403);
});
